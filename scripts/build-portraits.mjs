// Architect portraits: hand-drawn SVG sources in scripts/portraits/*.svg,
// baked into a TS module the app renders with SvgXml.
//
// Flat cut-paper figures on geometric label shapes, after the Showa-era
// travel labels. Every path coordinate gets a very small seeded wobble so the
// edges read as hand-cut rather than plotted.
//
//   node scripts/build-portraits.mjs  →  components/architect-portraits.generated.ts
import fs from "node:fs";
import path from "node:path";

const SRC = "scripts/portraits";
const OUT = "components/architect-portraits.generated.ts";
const WOBBLE = 0.45; // viewBox units: the slight irregularity of a hand-cut edge

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const entries = [];
for (const file of fs.readdirSync(SRC).filter((f) => f.endsWith(".svg")).sort()) {
  const key = path.basename(file, ".svg");
  const r = rng([...key].reduce((h, c) => h * 31 + c.charCodeAt(0), 7));
  let svg = fs.readFileSync(path.join(SRC, file), "utf8");
  svg = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<text[\s\S]*?<\/text>/g, "")
    // (Arcs would break: their flags are numbers too. Sources use curves only.)
    .replace(/ d="([^"]+)"/g, (_, d) => {
      const wobbled = d.replace(/-?\d+(\.\d+)?/g, (n) =>
        (parseFloat(n) + (r() - 0.5) * WOBBLE).toFixed(2).replace(/\.?0+$/, ""),
      );
      return ` d="${wobbled}"`;
    })
    // Ids must be unique per portrait when several share a page.
    .replace(/id="([^"]+)"/g, (_, id) => `id="${id}-${key}"`)
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${id}-${key})`)
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
  entries.push([key, svg]);
}

const body = entries.map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync(
  OUT,
  `// Generated by scripts/build-portraits.mjs — edit the SVGs in scripts/portraits.\n` +
    `export const PORTRAIT_SVG = {\n${body}\n} as const;\n`,
);
console.log(`wrote ${OUT} (${entries.map(([k]) => k).join(", ")})`);
