#!/usr/bin/env bash
# The pocket guide's typefaces as LVGL fonts: Jost in the weights and sizes the
# screens set (docs/tour-device-plan.md, "Screen design"), and Berkeley Post for
# the cover. Writes device/main/fonts/*.c and fonts.h.
#
# Run from the repo root: bash scripts/device/build-fonts.sh
set -euo pipefail

JOST=node_modules/@expo-google-fonts/jost
POST=assets/fonts/BerkeleyPost.otf
OUT=device/main/fonts
mkdir -p "$OUT"

# Printable ASCII, middle dot, e acute, em dash, right single quote.
TEXT=0x20-0x7E,0xB0,0xB7,0xE9,0x2014,0x2019,0x2026

font() { # name file size range
  npx --yes lv_font_conv --no-compress --bpp 4 --format lvgl \
    --font "$2" --range "$4" --size "$3" --lv-font-name "$1" -o "$OUT/$1.c" >/dev/null
  echo "LV_FONT_DECLARE($1);" >> "$OUT/fonts.h.tmp"
}

: > "$OUT/fonts.h.tmp"
font jost_medium_14   $JOST/500Medium/Jost_500Medium.ttf               14 $TEXT
font jost_medium_16   $JOST/500Medium/Jost_500Medium.ttf               16 $TEXT
font jost_regular_13  $JOST/400Regular/Jost_400Regular.ttf             13 $TEXT
font jost_regular_15  $JOST/400Regular/Jost_400Regular.ttf             15 $TEXT
font jost_regular_16  $JOST/400Regular/Jost_400Regular.ttf             16 $TEXT
font jost_regular_18  $JOST/400Regular/Jost_400Regular.ttf             18 $TEXT
font jost_regular_20  $JOST/400Regular/Jost_400Regular.ttf             20 $TEXT
font jost_regular_22  $JOST/400Regular/Jost_400Regular.ttf             22 $TEXT
font jost_medium_18   $JOST/500Medium/Jost_500Medium.ttf               18 $TEXT
font jost_light_italic_15 $JOST/300Light_Italic/Jost_300Light_Italic.ttf 15 $TEXT
font jost_light_italic_18 $JOST/300Light_Italic/Jost_300Light_Italic.ttf 18 $TEXT
font jost_light_25    $JOST/300Light/Jost_300Light.ttf                 25 $TEXT
font jost_light_28    $JOST/300Light/Jost_300Light.ttf                 28 $TEXT
font jost_light_32    $JOST/300Light/Jost_300Light.ttf                 32 $TEXT
font jost_light_58    $JOST/300Light/Jost_300Light.ttf                 58 0x20,0x30-0x39,0x6D
font jost_light_54    $JOST/300Light/Jost_300Light.ttf                 54 0x20,0x30-0x39
font jost_semibold_16 $JOST/600SemiBold/Jost_600SemiBold.ttf           16 $TEXT
font jost_semibold_24 $JOST/600SemiBold/Jost_600SemiBold.ttf           24 0x20,0x30-0x39,0x41-0x5A
font berkeley_post_46 $POST                                            46 0x20,0x41-0x5A

{
  echo "/* Generated by scripts/device/build-fonts.sh — do not edit. */"
  echo "#pragma once"
  echo "#include \"lvgl.h\""
  cat "$OUT/fonts.h.tmp"
} > "$OUT/fonts.h"
rm "$OUT/fonts.h.tmp"
ls "$OUT"
